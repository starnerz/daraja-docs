/**
 * Rebuilds `src/content/docs/changelog.md` from the package's CHANGELOG.md.
 *
 *   npm run sync:changelog            # from the package's default branch
 *   npm run sync:changelog -- ../laravel-daraja/CHANGELOG.md
 *
 * Release notes are cheap, indexable content that signals the package is
 * alive, so the docs carry a copy rather than linking away to GitHub.
 * Committed rather than fetched at build time: the deploy should not depend
 * on a network call to another repository.
 */
import { readFile, writeFile } from 'node:fs/promises';

const REMOTE = 'https://raw.githubusercontent.com/starnerz/laravel-daraja/master/CHANGELOG.md';
const OUT = new URL('../src/content/docs/changelog.md', import.meta.url);

const source = process.argv[2];

const raw = source
    ? await readFile(source, 'utf8')
    : await fetch(REMOTE).then((response) => {
          if (!response.ok) throw new Error(`${REMOTE} responded ${response.status}`);
          return response.text();
      });

const body = raw
    // The page title comes from frontmatter, so drop the file's own H1 and the
    // Keep a Changelog preamble beneath it.
    .replace(/^#\s+Changelog\s*\n+[\s\S]*?(?=^## )/m, '')
    // Point cross-links at the sibling pages, which keeps them correct
    // whichever domain and base path the site is served from.
    .replace(/https:\/\/starnerz\.github\.io\/daraja-docs\/([^)\s]+?)\/(?=[)\s])/g, './$1.md')
    .trim();

const frontmatter = [
    '---',
    'title: Changelog',
    'description: Every release of starnerz/laravel-daraja, and what changed in it.',
    '---',
    '',
    '<!-- Generated by `npm run sync:changelog` — edit the package CHANGELOG.md instead. -->',
    '',
    'Every release of [`starnerz/laravel-daraja`](https://packagist.org/packages/starnerz/laravel-daraja).',
    '',
].join('\n');

await writeFile(OUT, `${frontmatter}\n${body}\n`, 'utf8');

console.log(`Wrote ${OUT.pathname} (${body.length} characters)`);
